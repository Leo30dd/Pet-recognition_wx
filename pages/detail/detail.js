Page({
  data: {
    breedName: '',
    info: null
  },

  onLoad(options) {
    let name = options.breed;
    
    if(name && name.indexOf('(') > -1){
      name = name.split('(')[0].trim();
    }

    // 1. 尝试直接精确匹配
    let info = breedDatabase[name];
    
    // 2. 尝试模糊匹配 (比如传过来的是"贵宾犬/泰迪"，可以在这里拆分匹配)
    if (!info) {
      for (const key in breedDatabase) {
        if (name.includes(key) || key.includes(name)) {
          info = breedDatabase[key];
          name = key; // 用字典里的标准名字替换
          break;
        }
      }
    }

    // 3. 终极兜底逻辑 (万一后端识别出了字典里没写的狗)
    if (!info) {
      info = {
        tags: ['萌宠', '人类的好朋友'],
        intro: `这是一只可爱的 ${name}！我们正在努力完善它的专属百科资料，您可以先去搜索引擎了解更多关于它的有趣知识哦~`,
        care: '所有的狗狗都需要主人的耐心陪伴、科学的饮食和适量的运动。请用心爱护它！'
      };
    }

    this.setData({
      breedName: name,
      info: info
    });

    // 动态设置顶部导航栏的标题
    wx.setNavigationBarTitle({ title: name + ' 百科' });
  }
})