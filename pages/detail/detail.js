Page({
  data: {
    breedName: '',
    info: null
  },

  onLoad(options) {
    let name = options.breed;
    
    // 1. 处理名字：有些时候名字可能带有括号补充说明，去掉括号部分
    // 例如 "柯基犬 (彭布罗克)" -> "柯基犬"
    if(name && name.indexOf('(') > -1){
      name = name.split('(')[0].trim();
    }

    // 2. 查找数据库
    let info = breedDatabase[name];
    
    // 3. 模糊匹配 (容错机制)
    // 如果直接没找到，试着看看是不是包含关系
    if (!info) {
      for (const key in breedDatabase) {
        // 比如传进来是 "泰迪犬"，字典里有 "贵宾犬"，这里无法匹配，
        // 需要后端 app.py 里的映射做好。
        // 这里主要处理 "彭布罗克威尔士柯基" 匹配 "柯基犬" 这种情况
        if (name.includes(key) || key.includes(name)) {
          info = breedDatabase[key];
          name = key; 
          break;
        }
      }
    }

    // 4. 兜底逻辑 (万一没找到)
    if (!info) {
      info = {
        tags: ['萌宠', '可爱'],
        intro: `这是 ${name}，它非常可爱！暂无详细百科数据，你可以去搜索引擎查看更多关于它的信息。`,
        care: '请以此品种的通用饲养方式为准，多陪伴它是最好的照顾。'
      };
    }

    this.setData({
      breedName: name,
      info: info
    });

    // 设置顶部导航栏标题
    wx.setNavigationBarTitle({ title: name + '小百科' });
  }
})